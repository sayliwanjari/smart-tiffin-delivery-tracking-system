<?php

/*
|--------------------------------------------------------------------------
| Dabbawala Authentication
|--------------------------------------------------------------------------
| Protects all dabbawala dashboard pages.
|--------------------------------------------------------------------------
*/

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| Check Login
|--------------------------------------------------------------------------
*/

if (
    empty($_SESSION['dabbawala_id']) ||
    !is_numeric($_SESSION['dabbawala_id'])
) {
    header('Location: /mumbaiDabbawala/dabbawalas/login.php');
    exit;
}

/*
|--------------------------------------------------------------------------
| Dabbawala ID
|--------------------------------------------------------------------------
*/

$dabbawala_id = (int) $_SESSION['dabbawala_id'];

/*
|--------------------------------------------------------------------------
| Dabbawala Name
|--------------------------------------------------------------------------
*/

$dabbawala_name = $_SESSION['dabbawala_name'] ?? 'Dabbawala';

/*
|--------------------------------------------------------------------------
| Dabbawala Email
|--------------------------------------------------------------------------
*/

$dabbawala_email = $_SESSION['dabbawala_email'] ?? '';

/*
|--------------------------------------------------------------------------
| Dabbawala Status
|--------------------------------------------------------------------------
*/

$dabbawala_status = $_SESSION['dabbawala_status'] ?? 'active';

/*
|--------------------------------------------------------------------------
| Extra Safety Check
|--------------------------------------------------------------------------
*/

if ($dabbawala_status !== 'active') {

    session_unset();
    session_destroy();

    header('Location: /mumbaiDabbawala/dabbawalas/login.php');
    exit;
}


/*
|--------------------------------------------------------------------------
| Safe Output Helper
|--------------------------------------------------------------------------
*/

function dabbawala_e($value)
{
    return htmlspecialchars(
        (string) $value,
        ENT_QUOTES,
        'UTF-8'
    );
}